#!/usr/bin/env node
/* The English book.

   Every page under site/ gets a twin under site/en/. Not a language toggle
   that flips a few labels — the same pages, the same components, the same
   generated tables, in English and left-to-right, at their own URLs. That is
   how Material and HIG do it, and it is the only version a search engine or a
   non-Persian-reading developer can actually reach.

   The translation is a dictionary keyed by the Persian string itself
   (source/i18n/pages.json, plus source/i18n.mjs for specimen content), applied
   to the rendered HTML rather than to the builders. That choice is deliberate:
   the key is the exact sentence a reader sees, so a translation can never
   drift from the thing it translates, and build/dev/i18n-extract.mjs can list
   precisely what is still missing. A string with no entry stays Persian —
   visible, countable and honest, rather than silently dropped.

   What changes on an English page:
     lang / dir            fa/rtl → en/ltr
     text and labels       through the dictionary
     numerals              ۱۲۳ → 123, ٬ → , and ٫ → .
     asset paths           one level deeper, since /en/ is a directory
     canonical + alternate each page points at its twin, both ways */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync, existsSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { ROOT } from './tokens-lib.mjs';
import { fa2en } from '../source/i18n.mjs';
import { SITE_URL } from './site-lib.mjs';

const SITE = join(ROOT, 'site');
const EN = join(SITE, 'en');

const pagesDict = existsSync(join(ROOT, 'source/i18n/pages.json'))
  ? JSON.parse(readFileSync(join(ROOT, 'source/i18n/pages.json'), 'utf8')) : {};
/* Page strings win over specimen strings: a word can mean one thing in a
   product label and another in a sentence about the system. */
const DICT = { ...fa2en, ...pagesDict };

const PERSIAN = /[؀-ۿ]/;
const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
const toLatin = s => s
  .replace(/[۰-۹]/g, d => FA_DIGITS.indexOf(d))
  .replace(/٬/g, ',').replace(/٫/g, '.').replace(/٪/g, '%');

let hit = 0, miss = 0;
const missed = new Map();
const blockMiss = new Map();

function translate(raw) {
  const lead = raw.match(/^\s*/)[0], tail = raw.match(/\s*$/)[0];
  const s = raw.trim();
  if (!s || !PERSIAN.test(s)) return raw;
  const en = DICT[s];
  if (en !== undefined) { hit++; return lead + en + tail; }
  /* "۲۰ old Sketch names…" and "۸ old Sketch names…" are the same sentence
     with a different count in front. One entry covers every count. */
  const counted = /^([۰-۹٬,.\d]+)\s+(.+)$/s.exec(s);
  if (counted && DICT[counted[2]] !== undefined) {
    hit++;
    return lead + toLatin(counted[1]) + ' ' + DICT[counted[2]] + tail;
  }
  miss++;
  missed.set(s, (missed.get(s) ?? 0) + 1);
  /* No entry: keep the Persian, but the digits inside it are still digits. */
  return lead + toLatin(s) + tail;
}

/* ---- blocks first ----
   A sentence with a <code> or a <strong> inside it is one sentence, not three
   fragments. Persian and English put their words in different orders, so
   translating the fragments separately produces English that reads backwards
   around the tag. The key is therefore the whole block's inner HTML, and the
   translation is free to put the <code> wherever English wants it.

   Only leaf blocks — ones this book never nests inside themselves. */
const BLOCKS = ['p', 'li', 'td', 'th', 'h1', 'h2', 'h3', 'h4', 'h5', 'dd', 'dt', 'figcaption'];
const BLOCK_RE = BLOCKS.map(t => [t, new RegExp(`(<${t}(?:\\s[^>]*)?>)([^<]*(?:<(?!/?${t}[\\s>])[^>]*>[^<]*)*)(</${t}>)`, 'g')]);

function translateBlocks(html) {
  for (const [, re] of BLOCK_RE) {
    html = html.replace(re, (m, open, inner, close) => {
      const key = inner.trim();
      if (!key || !PERSIAN.test(key)) return m;
      const en = DICT[key];
      if (en === undefined) { blockMiss.set(key, (blockMiss.get(key) ?? 0) + 1); return m; }
      hit++;
      return open + en + close;
    });
  }
  return html;
}

/* ---- then any text node the blocks did not cover ----
   The HTML here is generated by this repository, so a tag-aware scan is enough
   and a DOM parser is not worth the dependency. What matters is never touching
   the inside of <pre>, <code>, <script>, <style> or an SVG path. */
const OPAQUE = /^(pre|code|script|style|svg)\b/i;

function translateText(html) {
  let out = '', i = 0, opaque = 0;
  while (i < html.length) {
    const lt = html.indexOf('<', i);
    if (lt === -1) { out += opaque ? html.slice(i) : translate(html.slice(i)); break; }
    const text = html.slice(i, lt);
    out += opaque ? text : translate(text);
    const gt = html.indexOf('>', lt);
    if (gt === -1) { out += html.slice(lt); break; }
    const tag = html.slice(lt, gt + 1);
    const name = tag.slice(1).replace(/^\//, '');
    if (OPAQUE.test(name)) opaque += tag[1] === '/' ? -1 : (tag.endsWith('/>') ? 0 : 1);
    if (opaque < 0) opaque = 0;
    out += opaque || !PERSIAN.test(tag) ? tag : translateAttrs(tag);
    i = gt + 1;
  }
  return out;
}

const ATTRS = ['aria-label', 'title', 'placeholder', 'alt', 'content', 'data-copy-text'];
function translateAttrs(tag) {
  return tag.replace(/([a-z-]+)="([^"]*)"/g, (m, a, v) =>
    ATTRS.includes(a) && PERSIAN.test(v) ? `${a}="${translate(v).replace(/"/g, '&quot;')}"` : m);
}

/* ---- the page shell ---- */
function englishShell(html, slug) {
  const depth = slug.split('/').length - 1;
  const up = '../'.repeat(depth);
  return html
    .replace('<html lang="fa" dir="rtl">', '<html lang="en" dir="ltr">')
    /* The specimen locale switch starts on English here, and site.js reads
       that as the initial state rather than defaulting back to Persian. */
    .replace('<body class="site">', '<body class="site" data-locale="en">')
    .replace('id="localeToggle" data-locale="fa"', 'id="localeToggle" data-locale="en"')
    .replace('<span id="localeLabel">فارسی</span>', '<span id="localeLabel">English</span>')
    .replace('<meta property="og:locale" content="fa_IR">', '<meta property="og:locale" content="en_US">')
    /* /en/ is one directory deeper than the Persian page it twins, so every
       asset reference gains one level. Page links are relative and already
       resolve inside /en/, which is what we want. */
    .replace(/(href|src)="((?:\.\.\/)*)assets\//g, '$1="../$2assets/')
    /* The machine-readable twins live at the site root, not per language. */
    .replace(/(href)="((?:\.\.\/)*)(llms(?:-full)?\.txt)"/g, '$1="../$2$3"')
    .replace(/<link rel="alternate" type="text\/markdown" href="[^"]*">/,
      `<link rel="alternate" type="text/markdown" href="${up}../${slug === 'index' ? 'index' : slug}.md">`)
    .replace(`<meta property="og:url" content="${SITE_URL}/`, `<meta property="og:url" content="${SITE_URL}/en/`)
    .replace('</head>', `<link rel="canonical" href="${SITE_URL}/en/${slug}.html">
<link rel="alternate" hreflang="fa" href="${SITE_URL}/${slug}.html">
<link rel="alternate" hreflang="en" href="${SITE_URL}/en/${slug}.html">
</head>`)
    /* The switch points home rather than at the twin's twin. */
    .replace(/<a class="site-lang[^>]*>[^<]*<\/a>/,
      `<a class="site-lang t-button t-button--outline t-button--sm" href="${up}../${slug}.html" hreflang="fa" lang="fa">فارسی</a>`);
}

/* ---- run ---- */
const pages = [];
(function walk(d) {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) { if (!p.includes('/assets') && p !== EN) walk(p); }
    else if (f.endsWith('.html')) pages.push(p.slice(SITE.length + 1));
  }
})(SITE);

mkdirSync(EN, { recursive: true });
for (const rel of pages) {
  const slug = rel.replace(/\.html$/, '');
  const html = readFileSync(join(SITE, rel), 'utf8');
  const out = englishShell(translateText(translateBlocks(html)), slug);
  const target = join(EN, rel);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, out);
}

/* The Persian pages carry the switch to here — and the other half of the
   pairing. An hreflang annotation only counts when it is reciprocal: a page
   that names its twin without being named back is discarded, so writing the
   links on the English side alone would have been the same as not writing
   them. Each side also declares its own canonical, or the pair reads as one
   page duplicated. */
for (const rel of pages) {
  const p = join(SITE, rel);
  const slug = rel.replace(/\.html$/, '');
  const depth = slug.split('/').length - 1;
  const html = readFileSync(p, 'utf8')
    .replace(/<a class="site-lang[^>]*>[^<]*<\/a>/,
      `<a class="site-lang t-button t-button--outline t-button--sm" href="${'../'.repeat(depth)}en/${rel}" hreflang="en" lang="en">English</a>`)
    .replace('</head>', `<link rel="canonical" href="${SITE_URL}/${slug}.html">
<link rel="alternate" hreflang="fa" href="${SITE_URL}/${slug}.html">
<link rel="alternate" hreflang="en" href="${SITE_URL}/en/${slug}.html">
</head>`);
  writeFileSync(p, html);
}

const rate = Math.round(hit / (hit + miss) * 100);
/* A block that is still Persian is worth more than a loose text node inside
   it, so blocks are listed first and the fragments they contain are dropped —
   translating the block is what actually fixes them. */
const blockKeys = [...blockMiss.keys()];
const looseMisses = [...missed.entries()].filter(([fa]) => !blockKeys.some(b => b.includes(fa)));
writeFileSync(join(ROOT, 'source/i18n/missing.json'),
  JSON.stringify([
    ...[...blockMiss.entries()].map(([fa, n]) => ({ fa, n, block: true })),
    ...looseMisses.map(([fa, n]) => ({ fa, n })),
  ].sort((a, b) => b.n * b.fa.length - a.n * a.fa.length), null, 1));
console.log(`✓ ${pages.length} English pages → site/en/`);
console.log(`  ${hit} strings translated, ${miss} still Persian — ${rate}% of placements`);
console.log(`  what is left: source/i18n/missing.json`);
