#!/usr/bin/env node
/* Apply the Farsi prose table to the component registry.
   Only prose fields are touched — specimen HTML, class names and React code
   are re-serialised byte-for-byte, so a translation pass can never damage code. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './tokens-lib.mjs';

const FILES = ['actions', 'inputs', 'navigation', 'commerce', 'feedback', 'overlays', 'data', 'layout'];
const fa = JSON.parse(readFileSync(join(ROOT, 'source/fa/components.json'), 'utf8'));

const ser = v => JSON.stringify(v, null, 2);

/* A dimension like ۳۴۳×۷۲ is a bidi-neutral run. Dropped into a Persian
   sentence the browser reorders it and the reader sees ۷۲×۳۴۳ — the numbers
   are right and the meaning is backwards. Isolate every such run. */
const DIMENSION = /(?<![>\w])([۰-۹0-9]+(?:٫[۰-۹0-9]+)?\s?[×x:]\s?[۰-۹0-9]+(?:٫[۰-۹0-9]+)?)(?![\w<])/g;
/* A Jalali date is neutral too, so ۱۴۰۴/۰۶/۱۳ تا ۱۴۰۴/۰۶/۱۹ swaps its ends. */
const DATE = /(?<![>\w])([۰-۹]{4}\/[۰-۹]{2}\/[۰-۹]{2})(?![\w<])/g;
const isolate = v => typeof v === 'string'
  ? v.replace(DIMENSION, '<span class="t-bidi" dir="ltr">$1</span>')
      .replace(DATE, '<span class="t-bidi" dir="ltr">$1</span>')
  : Array.isArray(v) ? v.map(isolate) : v;

let translated = 0, missing = [];

for (const f of FILES) {
  const path = join(ROOT, 'source/components', `${f}.mjs`);
  if (!existsSync(path)) continue;
  const mod = await import(`file://${path}?v=${Date.now()}`);
  const list = mod.default;

  for (const c of list) {
    const t = fa[c.name];
    if (!t) { missing.push(c.name); continue; }
    if (t.summary) c.summary = isolate(t.summary);
    if (t.description) c.description = isolate(t.description);
    if (t.use) c.use = isolate(t.use);
    if (t.avoid) c.avoid = isolate(t.avoid);
    if (t.responsive) c.responsive = isolate(t.responsive);
    if (t.a11y) c.a11y = isolate(t.a11y);
    if (t.anatomy) c.anatomy = c.anatomy.map((row, i) => [isolate(t.anatomy[i]?.[0] ?? row[0]), isolate(t.anatomy[i]?.[1] ?? row[1])]);
    if (t.props) c.props = c.props.map((row, i) => [row[0], row[1], row[2], isolate(t.props[i] ?? row[3])]);
    if (t.specimenLabels) c.specimens = c.specimens.map((s, i) => ({ ...s, label: t.specimenLabels[i] ?? s.label, note: isolate(t.specimenNotes?.[i] ?? s.note) }));
    translated++;
  }

  writeFileSync(path,
    `/* Generated by build/translate-components.mjs from source/fa/components.json.\n` +
    `   Prose is Farsi; specimen HTML, class names and React code are untouched.\n` +
    `   Edit the Farsi in source/fa/components.json, then re-run the script. */\n` +
    `export default ${ser(list)};\n`);
}

console.log(`✓ ${translated} components translated`);
if (missing.length) console.log(`  ⚠ no Farsi entry for: ${missing.join(', ')}`);
